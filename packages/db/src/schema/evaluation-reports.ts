import { index, jsonb, pgTable, text, timestamp, uniqueIndex } from 'drizzle-orm/pg-core';

/**
 * Append-only evaluation report history (day-07 §2.3).
 *
 * One row per generated window report. Reports are evidence *about the pipeline*,
 * so they follow the same rule as evidence and snapshots: never UPDATE or DELETE a
 * published report — a mistaken report is superseded by a *new* row (with the
 * corrected window/version), never edited in place (day-07 §6). `source_version`
 * attributes a trend to the code that produced it, so a precision drop across a
 * deploy boundary reads as a version signal rather than pipeline drift.
 *
 * The UNIQUE index on `(window_from, window_to, source_version)` makes re-running
 * the same window under the same code a no-op-at-the-DB level: the second insert
 * violates the constraint instead of silently duplicating a historical number.
 */
export const evaluationReports = pgTable(
  'evaluation_reports',
  {
    // UUIDv7, generated by the ReportStore on insert (day-07 §2.3).
    id: text('id').primaryKey(),
    window_from: timestamp('window_from', { withTimezone: true }).notNull(),
    window_to: timestamp('window_to', { withTimezone: true }).notNull(),
    generated_at: timestamp('generated_at', { withTimezone: true }).notNull().defaultNow(),
    // The full flat report (`{ window, generatedAt, lines }`) as a JSON document.
    report: jsonb('report').notNull(),
    source_version: text('source_version').notNull(),
  },
  (table) => [
    index('evaluation_reports_window_idx').on(table.window_from, table.window_to),
    uniqueIndex('evaluation_reports_window_source_unique').on(table.window_from, table.window_to, table.source_version),
  ],
);
